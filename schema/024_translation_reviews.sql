COMMENT ON TABLE public.translation_reviews IS
'Persistent state for multilingual translation review workflows.';


COMMENT ON COLUMN public.translation_reviews.review_id IS
'Stable application-level identifier for the translation workflow.';


COMMENT ON COLUMN public.translation_reviews.source_language IS
'Detected or explicitly supplied source language code; auto means unresolved.';


COMMENT ON COLUMN public.translation_reviews.target_language IS
'Requested destination language code or normalized language value.';


COMMENT ON COLUMN public.translation_reviews.original_text IS
'Original untranslated content.';


COMMENT ON COLUMN public.translation_reviews.translated_text IS
'Machine translated preview before optional manual editing.';


COMMENT ON COLUMN public.translation_reviews.edited_text IS
'Optional user-edited translation used after review.';


COMMENT ON COLUMN public.translation_reviews.source_review_id IS
'Optional identifier of the originating editorial or external review workflow.';


COMMENT ON COLUMN public.translation_reviews.metadata IS
'Extensible workflow metadata without coupling translation state to publication.';


COMMENT ON COLUMN public.translation_reviews.expires_at IS
'Expiration time for temporary translation workflow state.';


