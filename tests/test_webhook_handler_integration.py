# =========================================================
# TEST 30
# SOURCE EMOJIS AND FOREIGN MENTIONS ARE REMOVED
# DONYA24 BRAND ICONS ARE PRESERVED
# =========================================================

def test_formatter_keeps_only_donya24_format_icons():

    from core.formatter import (
        format_news
    )

    raw_text = (
        "تیتر خبر\n\n"
        "🇮🇷 این ایموجی متعلق به متن منبع است\n"
        "برای اطلاعات بیشتر "
        "@another_account را ببینید\n\n"
        "منبع نمونه\n"
        "🆔 @source_account"
    )

    result = (
        format_news(
            raw_text,
            source_title="منبع نمونه",
            source_username="source_account"
        )
    )

    # =====================================================
    # EMOJIهای منبع باید حذف شوند
    # =====================================================

    assert (
        "🇮🇷"
        not in result
    )

    assert (
        "🆔"
        not in result
    )

    # =====================================================
    # Mentionهای خارجی باید حذف شوند
    # =====================================================

    assert (
        "@another_account"
        not in result
    )

    assert (
        "@source_account"
        not in result
    )

    # =====================================================
    # نام منبع Forward نیز باید حذف شود
    # =====================================================

    assert (
        "منبع نمونه"
        not in result
    )

    # =====================================================
    # متن واقعی خبر نباید حذف شود
    # =====================================================

    assert (
        "این ایموجی متعلق به متن منبع است"
        in result
    )

    assert (
        "برای اطلاعات بیشتر"
        in result
    )

    # =====================================================
    # قالب دنیا ۲۴ باید باقی بماند
    # =====================================================

    assert (
        "❇️"
        in result
    )

    assert (
        "🔹"
        in result
    )

    # =====================================================
    # Bullet نباید دوبار شود
    # =====================================================

    assert (
        "🔹 🔹"
        not in result
    )
